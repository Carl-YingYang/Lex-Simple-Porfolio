"use client";

import { useEffect, useRef, type ReactNode } from "react";
import { cn } from "@/lib/utils";

interface RevealProps {
  children: ReactNode;
  className?: string;
  /** Transition delay in milliseconds — useful for staggered grids. */
  delay?: number;
}

/**
 * Lightweight scroll-reveal wrapper built on IntersectionObserver.
 * Adds `.reveal` / `.is-visible` classes defined in globals.css.
 *
 * The effect only toggles a class on the observed node (external-system
 * synchronization), so there are no re-renders and no hydration mismatches.
 * Fully disabled for users who prefer reduced motion (handled in CSS).
 */
export function Reveal({ children, className, delay = 0 }: RevealProps) {
  const ref = useRef<HTMLDivElement>(null);

  useEffect(() => {
    const el = ref.current;
    if (!el) return;

    if (typeof IntersectionObserver === "undefined") {
      // Very old browsers: show everything immediately.
      el.classList.add("is-visible");
      return;
    }

    const io = new IntersectionObserver(
      (entries) => {
        for (const entry of entries) {
          if (entry.isIntersecting) {
            el.classList.add("is-visible");
            io.disconnect();
          }
        }
      },
      { threshold: 0.12, rootMargin: "0px 0px -48px 0px" }
    );

    io.observe(el);
    return () => io.disconnect();
  }, []);

  return (
    <div
      ref={ref}
      className={cn("reveal", className)}
      style={delay ? { transitionDelay: `${delay}ms` } : undefined}
    >
      {children}
    </div>
  );
}
